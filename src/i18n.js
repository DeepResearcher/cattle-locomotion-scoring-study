export function translate(language, key, values={}) {
  const template=messages[language]?.[key] ?? messages.de[key];
  if(typeof template!=='string') throw new Error(`Unknown translation: ${key}`);
  return template.replace(/\{(\w+)\}/g,(_,name)=>String(values[name] ?? ''));
}

export function translateOption(language, value) {
  return optionLabels[language]?.[value] ?? value;
}

export function translateError(language, message) {
  return language==='de' ? (germanErrors[message] ?? message) : message;
}
